# -*- coding: utf-8 -*-
"""Мраморная плита для фона разворота «Технология».

Фон — фотография настоящего камня. Прежняя, найденная заказчиком,
была обойной миниатюрой 736×1313: на полосе в 1900 точек её
приходилось тянуть в два с половиной раза, и никакая подрезка
мыла не убирала — растянутого пикселя не вернуть.

Эта снята с Pexels (снимок № 5623225, лицензия Pexels: можно
брать бесплатно, в том числе в коммерческом деле, без указания
автора). Исходник 4608×3072, и это меняет всё: до нужного
размера картинку не растягивают, а **ужимают** втрое. Ужатие
резкость не отнимает, а прибавляет.

Рисунок выбран по образцу: густая ломаная сеть жил с ясным
зерном — всё идёт снизу слева наверх направо.

Что делает скрипт:

  1. Обрезка до пропорции полосы. Исходник — широкий кадр 3:2,
     полоса почти квадратная; берётся середина по ширине.

  2. Баланс белого. Камень на снимке синит: по каналам 203 / 211
     / 221 при съёмке в тени. Зелёный и синий прижимаются к
     красному по девяносто восьмому процентилю — правится не
     средний тон, а именно света, иначе жилы уходят в охру.

  3. Растяжка тона. Снимок плоский: первый процентиль 122,
     девяносто пятый 228 — ни чёрного, ни белого. Уровни тянут
     полтора процента снизу в 12, девяносто девять сверху в 252,
     и поверх идёт мягкая ступень в треть силы. Жилы садятся в
     чёрное, камень становится белым, серый разбор между ними
     остаётся.

  4. Ужатие Ланцошем и подрезка после него — в таком порядке, а
     не наоборот: подрезать до ужатия значит выбросить работу.

  5. Зерно в полторы единицы против полос webp на гладких полях.

Про вес. Мрамор сжимается плохо: мелкая крошка камня — это как
раз то, на что уходят биты. При 2200 точках и quality 80 файл
весит 850 КБ, и рядом с остальными картинками разворота (46–107
КБ) это перебор. Взято 2000 точек при quality 72 — 600 КБ.
Ниже опускаться нельзя: на 1900 точках полосы картинка ложится
почти один к одному, а при меньшей ширине её снова начинает
растягивать браузер, и весь смысл замены пропадает.
"""
import numpy as np
from PIL import Image, ImageFilter

SRC = "mramor-ishodnik.jpg"
OUT = "assets/img/marble.webp"
W, H = 2000, 2110             # пропорция полосы, с небольшим запасом

src = Image.open(SRC).convert("RGB")

# ---- 1. обрезка до пропорции полосы --------------------------
need = W / H
cw = min(src.width, int(round(src.height * need)))
ch = min(src.height, int(round(cw / need)))
x0 = (src.width - cw) // 2
y0 = (src.height - ch) // 2
img = src.crop((x0, y0, x0 + cw, y0 + ch))

a = np.asarray(img, dtype=np.float32)

# ---- 2. баланс белого по светам ------------------------------
ref = np.percentile(a[:, :, 0], 98)
for c in (1, 2):
    p = np.percentile(a[:, :, c], 98)
    a[:, :, c] *= ref / p

# ---- 3. растяжка тона ----------------------------------------
lum = a.mean(axis=2, keepdims=True)
lo, hi = np.percentile(lum, 1.5), np.percentile(lum, 99.0)
t = np.clip((lum - lo) / (hi - lo), 0.0, 1.0)
straight = 12.0 + t * 240.0
step = 12.0 + (t * t * (3.0 - 2.0 * t)) * 240.0
target = straight * 0.66 + step * 0.34
a = np.clip(a + (target - lum), 0.0, 255.0)

# ---- 4. ужатие и подрезка ------------------------------------
img = Image.fromarray(a.astype(np.uint8), "RGB").resize((W, H), Image.LANCZOS)
img = img.filter(ImageFilter.UnsharpMask(radius=1.1, percent=75, threshold=2))

# ---- 5. зерно ------------------------------------------------
rng = np.random.default_rng(17)
a = np.asarray(img, dtype=np.float32) + rng.normal(0.0, 1.5, (H, W, 3))
out = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "RGB")
out.save(OUT, quality=72, method=6)

g = np.asarray(out.convert("L"), dtype=np.float32)
print("%dx%d  mean %.0f  std %.0f  p1 %.0f  p99 %.0f"
      % (W, H, g.mean(), g.std(), np.percentile(g, 1), np.percentile(g, 99)))
