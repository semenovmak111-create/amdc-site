# -*- coding: utf-8 -*-
"""Мраморные плиты для фона разворота «Технология».

Скрипт собирает два фона. Основной стоит на самой странице,
второй — на отдельной странице сравнения
`tehnologiya-staryy-mramor.html`, где тот же разворот показан на
другом камне. Кадры разные по устройству, и обходятся они тоже
по-разному.

  РАМКА — `mramor-ishodnik.jpg` → `assets/img/marble.webp`

Кадр построен рамкой: чёрные жилы-молнии стоят двумя группами по
левому и правому краю, по самым краям — тонкие золотые жилы в тон
цепи между карточками, середина оставлена пустой, там лежат восемь
карточек.

Тон править не пришлось: исходник нейтральный, белое на 251,
чёрное на 8. Осталась одна геометрия — растяжка до 2000×2110,
пропорции полосы (на десктопе она 1904×2005, почти квадрат).
Растяжка неравномерная: по ширине кадр ужимается втрое от 2752,
по высоте тянется в 1.37 раза от 1536.

Подрезать вместо растяжки нельзя, и в этом вся суть. Центральный
кадр в пропорции полосы — это 1456 точек из 2752, то есть ровно
пустая середина: все жилы остались бы за кадром, а на полосе
оказался бы белый лист. Растяжение же идёт вдоль жил — они
вертикальные, — и на глаз не читается вовсе.

  ДИАГОНАЛЬ — `mramor-diagonal-ishodnik.jpg`
                          → `assets/img/marble-diagonal.webp`

Здесь рисунок сплошной: ломаная сеть серых жил идёт снизу слева
наверх направо, с двумя раздробленными гнёздами. Пустых мест в
кадре нет, поэтому его как раз подрезают — центральный кадр
1456×1536 в пропорции полосы, оба гнезда остаются в поле.

Этот снимок синит (по 99-му процентилю 242 / 244 / 248) и стоит
светами на 240, отчего камень читается серым. Поэтому, в отличие
от первого, ему нужны и баланс белого, и растяжка светов в 252.
Тени не трогаем: они и так на 7.

Общее у обоих — Ланцош и слабая нерезкая маска после него, и
никакого зерна. Зерно было бедой прежнего фона с Pexels: его
сыпали против полос webp, а на полосе оно читалось как мыло. На
гладком рисунке webp обходится без него.
"""
import numpy as np
from PIL import Image, ImageFilter

W, H = 2000, 2110             # пропорция полосы, с небольшим запасом
SHARP = dict(radius=1.4, percent=50, threshold=2)


def sharpen_save(img, out, quality):
    img = img.filter(ImageFilter.UnsharpMask(**SHARP))
    img.save(out, quality=quality, method=6)


# ---- рамка: растяжка без подрезки ----------------------------
ramka = Image.open("mramor-ishodnik.jpg").convert("RGB")
sharpen_save(ramka.resize((W, H), Image.LANCZOS), "assets/img/marble.webp", 92)

# ---- диагональ: подрезка, баланс белого, света ---------------
src = Image.open("mramor-diagonal-ishodnik.jpg").convert("RGB")
cw = int(round(src.height * (W / H)))
x0 = (src.width - cw) // 2
a = np.asarray(src.crop((x0, 0, x0 + cw, src.height))).astype(np.float32)

ref = np.percentile(a[..., 0], 99)
for i in (1, 2):
    a[..., i] *= ref / np.percentile(a[..., i], 99)

lo, hi = 4.0, float(np.percentile(a, 99.6))
a = np.clip((a - lo) * (252.0 / (hi - lo)), 0, 255)

diag = Image.fromarray(a.astype(np.uint8)).resize((W, H), Image.LANCZOS)
sharpen_save(diag, "assets/img/marble-diagonal.webp", 86)
