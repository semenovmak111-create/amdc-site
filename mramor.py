# -*- coding: utf-8 -*-
"""Мраморная плита для фона разворота «Технология».

Фон — фотография камня. Прежняя, снятая с Pexels, была настоящим
камнем, но снятым в тень и с крупным зерном: чтобы зерно не пошло
полосами в webp, в неё досыпали ещё полторы единицы своего, и на
полосе вся эта крошка читалась как мыло. Кадр заменён на рисованный
(nanobanana, 2752×1536): рисунок тот же — ломаная сеть жил снизу
слева наверх направо, с двумя раздробленными гнёздами, — но края
жил чистые, а белые поля гладкие.

Что делает скрипт:

  1. Центральный кадр в пропорции полосы. Полоса на десктопе —
     1904×2005, почти квадрат; исходник широкий, 16:9. Берётся
     середина по ширине: 1456×1536. Оба гнезда остаются в кадре.

  2. Баланс белого. Камень синит: по 99-му процентилю 242 / 244 /
     248. Зелёный и синий прижимаются к красному — правятся именно
     света, иначе жилы уходят в охру.

  3. Света к белому. Верх снимка стоит на 240, из-за чего камень
     читается серым; уровни тянут 240 в 252. Тени не трогаем: они
     и так на 7, жилы чёрные.

  4. Растяжка Ланцошем до 2000×2110 и слабая нерезкая маска.
     Растяжка здесь неизбежна: полоса почти квадратная, а исходник
     широкий, и по высоте его в любом случае тянуть в 1.37 раза.
     Лучше растянуть Ланцошем с маской один раз тут, чем отдать это
     браузеру на каждом экране.

  5. Зерна не сыплем. Оно и было причиной замены; на гладком
     рисунке webp обходится без него, полос при quality 86 нет.

Вес — 517 КБ против прежних 601 КБ. Ниже 80 опускаться нельзя:
на белых полях появляется ступенька.
"""
import numpy as np
from PIL import Image, ImageFilter

SRC = "mramor-ishodnik.jpg"
OUT = "assets/img/marble.webp"
W, H = 2000, 2110             # пропорция полосы, с небольшим запасом

src = Image.open(SRC).convert("RGB")

# ---- 1. центральный кадр в пропорции полосы ------------------
cw = int(round(src.height * (W / H)))
crop = src.crop(((src.width - cw) // 2, 0, (src.width - cw) // 2 + cw, src.height))

a = np.asarray(crop).astype(np.float32)

# ---- 2. баланс белого по 99-му процентилю --------------------
ref = np.percentile(a[..., 0], 99)
for i in (1, 2):
    a[..., i] *= ref / np.percentile(a[..., i], 99)

# ---- 3. света к белому, тени на месте ------------------------
lo, hi = 4.0, float(np.percentile(a, 99.6))
a = np.clip((a - lo) * (252.0 / (hi - lo)), 0, 255)

# ---- 4. растяжка и нерезкая маска ----------------------------
img = Image.fromarray(a.astype(np.uint8)).resize((W, H), Image.LANCZOS)
img = img.filter(ImageFilter.UnsharpMask(radius=1.6, percent=58, threshold=2))

img.save(OUT, quality=86, method=6)
