# -*- coding: utf-8 -*-
"""Мраморная плита для фона разворота «Технология».

Заказчик дал фотографию и попросил поставить фоном именно её,
только резче. Исходник — `mramor-ishodnik.jpg`, 736×1313: это
обойная миниатюра, и на полосе шириной в 1900 точек её надо
растянуть в два с половиной раза. Прямое растяжение даёт мыло,
поэтому здесь не одно действие, а цепочка.

  1. Снятие звона. JPEG в 130 КБ на 736 точках оставляет вокруг
     каждой чёрной жилы светлый ореол и сетку 8×8. Лечится
     слабым медианным проходом по самым плоским местам: маска
     плоскости — размах в окрестности, и там, где он мал (белый
     камень), берётся медиана, а где велик (кромка жилы) —
     исходный пиксель. Так шум уходит, а кромка остаётся.

  2. Растяжение в два приёма, а не в один. Ланцош на большом
     скачке размазывает кромку; два шага по корню из нужного
     множителя с подрезкой между ними держат её собранной.

  3. Подрезка в два радиуса. Средний (4 точки, слабый) даёт
     камню объём, малый (1.3, сильный) собирает кромку жилы.
     Большой радиус тут пробовался и снят: он поднимает светлую
     сторону каждой крупной кромки, и серые разводы — та самая
     мягкая муть, ради которой фотография и выбрана, — уходят в
     белую бумагу.

  4. S-кривая по светлоте. Чёрные жилы на исходнике сидят около
     сорока единиц, а не в нуле — фотография снята с заливкой.
     Кривая роняет тени и поднимает света, оставляя середину на
     месте: жила становится чёрной, камень белым, серый разбор
     между ними сохраняется.

  5. Зерно в полторы единицы. В webp большие плоские поля идут
     полосами, зерно их разбивает и стоит две-три килобайта.

Готовый файл кладётся рядом с остальными картинками.
"""
import numpy as np
from PIL import Image, ImageFilter

SRC = "mramor-ishodnik.jpg"
OUT = "assets/img/marble.webp"
W, H = 1900, 3390            # ровно тот размер, каким полоса его показывает

src = Image.open(SRC).convert("RGB")
a = np.asarray(src, dtype=np.float32)

# ---- 1. звон и сетка JPEG ------------------------------------
med = np.asarray(src.filter(ImageFilter.MedianFilter(3)), dtype=np.float32)
lo = np.asarray(src.convert("L").filter(ImageFilter.MinFilter(5)), np.float32)
hi = np.asarray(src.convert("L").filter(ImageFilter.MaxFilter(5)), np.float32)
flat = np.clip(1.0 - (hi - lo) / 34.0, 0.0, 1.0)[:, :, None]   # 1 — плоско
a = a * (1.0 - flat) + med * flat
img = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "RGB")

# ---- 2. растяжение в два приёма ------------------------------
mid = (int(round(src.width * (W / src.width) ** 0.5)),
       int(round(src.height * (H / src.height) ** 0.5)))
img = img.resize(mid, Image.LANCZOS)
img = img.filter(ImageFilter.UnsharpMask(radius=1.6, percent=70, threshold=2))
img = img.resize((W, H), Image.LANCZOS)

# ---- 3. подрезка в два радиуса -------------------------------
img = img.filter(ImageFilter.UnsharpMask(radius=4, percent=26, threshold=3))
img = img.filter(ImageFilter.UnsharpMask(radius=1.3, percent=115, threshold=2))

# ---- 4. S-кривая по светлоте ---------------------------------
# Замер исходника: пятый процентиль 120, пятидесятый 229,
# девяносто пятый 248. То есть камень занимает верхнюю треть
# шкалы, а жилы размазаны по всей нижней — картинка снята со
# светлой заливкой и потому плоская. Кривая растягивает её на
# всю шкалу: 0.10 уходит в ноль, 0.97 в единицу, середина
# поджимается смягчённой ступенью. Полностью ступень не берётся
# — серый разбор внутри жилы тогда схлопывается в пятно;
# берётся две трети от неё.
a = np.asarray(img, dtype=np.float32) / 255.0
lum = a.mean(axis=2, keepdims=True)
t = np.clip((lum - 0.06) / 0.94, 0.0, 1.0)
target = t
a = np.clip(a + (target - lum), 0.0, 1.0)

# ---- 5. зерно ------------------------------------------------
rng = np.random.default_rng(17)
a = a * 255.0 + rng.normal(0.0, 1.5, a.shape)
out = Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "RGB")
out.save(OUT, quality=78, method=6)

g = np.asarray(out.convert("L"), dtype=np.float32)
print("%dx%d  mean %.0f  std %.0f  min %.0f  max %.0f"
      % (W, H, g.mean(), g.std(), g.min(), g.max()))
