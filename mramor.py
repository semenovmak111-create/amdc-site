# -*- coding: utf-8 -*-
"""Мраморная плита для фона разворота «Технология».

Кадр рисованный (nanobanana, 2752×1536). Он построен рамкой: чёрные
жилы-молнии стоят двумя группами по левому и правому краю, между ними
широкое пустое поле белого камня, а по самым краям — несколько тонких
золотых жил в тон цепи, которая вьётся между карточками. Середина
пустая не случайно: там лежат восемь карточек, и любой рисунок под
ними только мешал бы.

Тон исходника править не пришлось: он нейтральный (по каналам 251 /
251 / 251 в светах), белое стоит на 251, чёрное на 8. Прежний кадр,
снятый с Pexels, требовал и баланса белого, и растяжки уровней, и
зерна против полос webp — здесь ничего этого не нужно.

Единственное, что делает скрипт, — геометрия:

  1. Растяжка до 2000×2110 — пропорции полосы (на десктопе она
     1904×2005, почти квадрат). Растяжка неравномерная: по ширине
     кадр ужимается втрое от 2752 (резкость от этого только растёт),
     по высоте тянется в 1.37 раза от 1536.

     Подрезать вместо растяжки нельзя, и в этом вся суть. Центральный
     кадр в пропорции полосы — это 1456 точек из 2752, то есть ровно
     пустая середина: все жилы остались бы за кадром, а на полосе
     оказался бы белый лист. Растяжение же идёт вдоль жил — они
     вертикальные, — и на глаз не читается вовсе.

  2. Слабая нерезкая маска после растяжки.

Зерно не сыплем: рисунок гладкий, при quality 92 полос на белых полях
нет, а весит файл всего 358 КБ — вдвое меньше прежних 601.

На телефоне полоса узкая и очень длинная, и там cover показал бы из
кадра ленту в одну шестую ширины — опять пустую середину. Поэтому в
mobile.css фон переключён на `100% 100%`: кадр не подрезается, а
тянется по высоте.
"""
from PIL import Image, ImageFilter

SRC = "mramor-ishodnik.jpg"
OUT = "assets/img/marble.webp"
W, H = 2000, 2110             # пропорция полосы, с небольшим запасом

img = Image.open(SRC).convert("RGB").resize((W, H), Image.LANCZOS)
img = img.filter(ImageFilter.UnsharpMask(radius=1.4, percent=50, threshold=2))
img.save(OUT, quality=92, method=6)
